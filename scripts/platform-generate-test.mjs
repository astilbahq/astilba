import assert from "node:assert/strict";
import {
  lstat,
  mkdir,
  mkdtemp,
  readFile,
  rm,
  symlink,
  writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import test from "node:test";
import { syncSQLC } from "./platform-generated-files.mjs";

const generated = (body) =>
  `// Code generated by sqlc. DO NOT EDIT.\n${body}\n`;

async function fixture(t) {
  const root = await mkdtemp(join(tmpdir(), "astilba-sqlc-test-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  const source = join(root, "source");
  const destination = join(root, "destination");
  await mkdir(source);
  await mkdir(destination);
  return { root, source, destination };
}

test("freshness checks see obsolete sqlc output; generation cleans only owned files", async (t) => {
  const { root, source, destination } = await fixture(t);
  await writeFile(join(source, "current.go"), generated("new output"));
  await writeFile(join(destination, "current.go"), generated("old output"));
  await writeFile(join(destination, "removed.sql.go"), generated("obsolete"));
  await writeFile(join(destination, "custom.go"), "package db\n");
  await mkdir(join(destination, "custom"));
  const outside = join(root, "outside.go");
  await writeFile(outside, generated("external"));
  await symlink(outside, join(destination, "unrelated.go"));

  await assert.rejects(syncSQLC(source, destination, true), /Obsolete/);
  assert.equal(
    await readFile(join(destination, "current.go"), "utf8"),
    generated("old output"),
  );
  assert.equal(
    await readFile(join(destination, "removed.sql.go"), "utf8"),
    generated("obsolete"),
  );

  await syncSQLC(source, destination, false);
  await syncSQLC(source, destination, true);
  assert.equal(
    await readFile(join(destination, "current.go"), "utf8"),
    generated("new output"),
  );
  await assert.rejects(lstat(join(destination, "removed.sql.go")), {
    code: "ENOENT",
  });
  assert.equal(
    await readFile(join(destination, "custom.go"), "utf8"),
    "package db\n",
  );
  assert.equal((await lstat(join(destination, "custom"))).isDirectory(), true);
  assert.equal(
    (await lstat(join(destination, "unrelated.go"))).isSymbolicLink(),
    true,
  );
  assert.equal(await readFile(outside, "utf8"), generated("external"));
});

test("expected output collisions never overwrite handwritten files or symlink targets", async (t) => {
  for (const kind of ["handwritten", "symlink"]) {
    await t.test(kind, async (t) => {
      const { root, source, destination } = await fixture(t);
      const outside = join(root, "outside.go");
      await writeFile(join(source, "models.go"), generated("new output"));
      await writeFile(
        join(destination, "removed.sql.go"),
        generated("obsolete"),
      );
      await writeFile(outside, "handwritten\n");
      if (kind === "symlink")
        await symlink(outside, join(destination, "models.go"));
      else await writeFile(join(destination, "models.go"), "handwritten\n");
      for (const check of [true, false])
        await assert.rejects(syncSQLC(source, destination, check), /Refusing/);
      assert.equal(
        await readFile(join(destination, "models.go"), "utf8"),
        "handwritten\n",
      );
      assert.equal(await readFile(outside, "utf8"), "handwritten\n");
      assert.equal(
        await readFile(join(destination, "removed.sql.go"), "utf8"),
        generated("obsolete"),
      );
    });
  }
});

test("generation refuses a symlink output directory", async (t) => {
  const { root, source, destination } = await fixture(t);
  await writeFile(join(source, "models.go"), generated("new output"));
  const linked = join(root, "linked");
  await symlink(destination, linked);
  await assert.rejects(syncSQLC(source, linked, false), /regular directory/);
  await assert.rejects(lstat(join(destination, "models.go")), {
    code: "ENOENT",
  });
});

test("filesystem filename aliases cannot overwrite or delete current output", async (t) => {
  for (const kind of ["handwritten", "owned"]) {
    await t.test(kind, async (t) => {
      const { source, destination } = await fixture(t);
      const original =
        kind === "owned" ? generated("old output") : "handwritten\n";
      await writeFile(join(source, "models.go"), generated("new output"));
      await writeFile(join(destination, "MODELS.go"), original);
      const alias = await lstat(join(destination, "models.go")).catch(
        (error) => {
          if (error.code !== "ENOENT") throw error;
          return null;
        },
      );
      if (alias) {
        for (const check of [true, false])
          await assert.rejects(
            syncSQLC(source, destination, check),
            /filesystem alias/,
          );
        assert.equal(
          await readFile(join(destination, "MODELS.go"), "utf8"),
          original,
        );
      } else {
        // Case-sensitive filesystems have two independent names and owners.
        await syncSQLC(source, destination, false);
        await syncSQLC(source, destination, true);
        assert.equal(
          await readFile(join(destination, "models.go"), "utf8"),
          generated("new output"),
        );
        if (kind === "owned")
          await assert.rejects(lstat(join(destination, "MODELS.go")), {
            code: "ENOENT",
          });
        else
          assert.equal(
            await readFile(join(destination, "MODELS.go"), "utf8"),
            original,
          );
      }
    });
  }
});
