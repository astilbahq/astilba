import {
  lstat,
  mkdir,
  readdir,
  readFile,
  unlink,
  writeFile,
} from "node:fs/promises";
import { join } from "node:path";

const header = Buffer.from("// Code generated by sqlc. DO NOT EDIT.\n");
const owned = (data) => data.subarray(0, header.length).equals(header);

export async function syncSQLC(source, destination, check) {
  const expected = new Map();
  for (const entry of await readdir(source, { withFileTypes: true })) {
    if (!entry.isFile())
      throw new Error(`Unexpected sqlc output: ${entry.name}`);
    const data = await readFile(join(source, entry.name));
    if (!owned(data))
      throw new Error(`Unrecognized sqlc output: ${entry.name}`);
    expected.set(entry.name, data);
  }

  let entries = [];
  try {
    if (!(await lstat(destination)).isDirectory())
      throw new Error("sqlc destination must be a regular directory");
    entries = await readdir(destination, { withFileTypes: true });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }

  const existing = new Map();
  for (const entry of entries) {
    if (entry.isFile()) {
      const data = await readFile(join(destination, entry.name));
      if (owned(data)) {
        existing.set(entry.name, data);
        continue;
      }
    }
    if (expected.has(entry.name))
      throw new Error(`Refusing to overwrite non-sqlc output: ${entry.name}`);
  }

  const obsolete = [...existing.keys()].filter((name) => !expected.has(name));
  const names = new Set(entries.map((entry) => entry.name));
  for (const name of expected.keys()) {
    if (names.has(name)) continue;
    try {
      await lstat(join(destination, name));
      throw new Error(`Refusing filesystem alias for sqlc output: ${name}`);
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
  }
  if (check) {
    if (obsolete.length)
      throw new Error(`Obsolete generated sqlc output: ${obsolete.join(", ")}`);
    for (const [name, data] of expected) {
      if (!existing.has(name) || !data.equals(existing.get(name)))
        throw new Error(`Stale or missing generated sqlc output: ${name}`);
    }
    return;
  }

  await mkdir(destination, { recursive: true });
  for (const [name, data] of expected)
    await writeFile(join(destination, name), data);
  for (const name of obsolete) await unlink(join(destination, name));
}
