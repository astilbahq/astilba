import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { download } from "./fetch-attempts.mjs";
import { minimumAgeMs } from "./go-release-age.mjs";

// Pins services/platform/internal/publicsuffix to one commit of the Public Suffix List.
// golang.org/x/net refreshes its copy about once a year, which is too slow for a new
// entry to reach a release. See docs/hosting.md#the-pinned-list.
//
//   node scripts/public-suffix-list.mjs          pin the newest eligible commit
//   node scripts/public-suffix-list.mjs --check  confirm the files match the pin
//
// The list's header asks for routine pulls from publicsuffix.org, which serves only
// the latest copy. This takes a reviewed commit a few times a year instead, so the pin
// can be checked against main's history, the release-age gate and upstream's bytes.

const root = resolve(import.meta.dirname, "..");
const target = resolve(root, "services/platform/internal/publicsuffix");
const api = "https://api.github.com/repos/publicsuffix/list";
const raw = "https://raw.githubusercontent.com/publicsuffix/list";
const files = [
  ["public_suffix_list.dat", "public_suffix_list.dat"],
  ["test_psl.txt", "tests/test_psl.txt"],
];
const updates = ["push", "force_push", "pr_merge", "merge_queue_merge"];

// The gate counts from when GitHub saw the commit become main's tip. A commit's own
// dates are set by whoever made it, so they could make a fresh commit look old.
export function chooseCommit(activities, now, minimumMs) {
  const eligible = activities.filter(
    (a) =>
      a.ref === "refs/heads/main" &&
      updates.includes(a.activity_type) &&
      Date.parse(a.timestamp) <= now - minimumMs,
  );
  if (eligible.length === 0)
    throw new Error("no update to publicsuffix/list main is older than the release-age gate");
  return eligible.reduce((newest, a) =>
    Date.parse(a.timestamp) > Date.parse(newest.timestamp) ? a : newest,
  );
}

export function sourceFile({ sha, pushed }) {
  return `// Code generated by scripts/public-suffix-list.mjs. DO NOT EDIT.

package publicsuffix

// The commit of github.com/publicsuffix/list that public_suffix_list.dat and
// test_psl.txt were copied from, unchanged, and when it became main's tip.
const (
	listCommit = "${sha}"
	listPushed = "${pushed}"
)
`;
}

export function pinnedCommit(source) {
  const sha = /^\tlistCommit = "([0-9a-f]{40})"$/m.exec(source)?.[1];
  if (!sha) throw new Error("source.go names no commit");
  return sha;
}

const json = async (url) => JSON.parse((await download(url)).toString("utf8"));
const upstream = (sha) =>
  Promise.all(files.map(([, path]) => download(`${raw}/${sha}/${path}`)));

async function pin() {
  const now = Date.now();
  const minimumMs = minimumAgeMs(readFileSync(resolve(root, "pnpm-workspace.yaml"), "utf8"));
  const activities = await json(`${api}/activity?ref=refs/heads/main&per_page=100`);
  const { after: sha, timestamp: pushed } = chooseCommit(activities, now, minimumMs);
  // A later force push can drop a commit that was once main's tip.
  const { status } = await json(`${api}/compare/${sha}...main`);
  if (!["ahead", "identical"].includes(status))
    throw new Error(`${sha} is no longer on publicsuffix/list main`);
  const downloaded = await upstream(sha);
  if (!downloaded[0].includes("// ===BEGIN PRIVATE DOMAINS==="))
    throw new Error("the downloaded list has no private section");
  files.forEach(([name], i) => writeFileSync(resolve(target, name), downloaded[i]));
  writeFileSync(resolve(target, "source.go"), sourceFile({ sha, pushed }));
  console.log(`Public Suffix List pinned to ${sha}, main's tip since ${pushed}`);
}

// The pin is only as good as the files' match with upstream; a hand edit to both the
// list and source.go would otherwise pass every offline check.
async function check() {
  const sha = pinnedCommit(readFileSync(resolve(target, "source.go"), "utf8"));
  const downloaded = await upstream(sha);
  files.forEach(([name], i) => {
    if (!readFileSync(resolve(target, name)).equals(downloaded[i]))
      throw new Error(`${name} differs from publicsuffix/list at ${sha}; run node scripts/public-suffix-list.mjs`);
  });
  console.log(`Public Suffix List matches publicsuffix/list at ${sha}`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await (process.argv[2] === "--check" ? check() : pin());
}
