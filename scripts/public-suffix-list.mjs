import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { download } from "./fetch-attempts.mjs";
import { minimumAgeMs } from "./go-release-age.mjs";

// Pins services/platform/internal/publicsuffix to one commit of the Public Suffix List.
// golang.org/x/net refreshes its copy about once a year, which is too slow for a new
// entry to reach a release. See docs/hosting.md#generated-application-names.
//
//   node scripts/public-suffix-list.mjs [commit]
//
// Without a commit it takes the newest one on main that is older than the release-age
// gate in pnpm-workspace.yaml. A commit given by hand passes the same gate.
//
// The list's header asks for routine pulls from publicsuffix.org, which serves only
// the latest copy. This takes a reviewed commit a few times a year instead, so the pin
// can be checked against main's history and the release-age gate.

const root = resolve(import.meta.dirname, "..");
const target = resolve(root, "services/platform/internal/publicsuffix");
const api = "https://api.github.com/repos/publicsuffix/list";
const raw = "https://raw.githubusercontent.com/publicsuffix/list";
const files = [
  ["public_suffix_list.dat", "public_suffix_list.dat"],
  ["test_psl.txt", "tests/test_psl.txt"],
];

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

// GitHub serves a commit pushed to any fork under the upstream repository's name, so a
// commit counts only when main contains it.
export function checkCommit({ sha, committed, comparison, now, minimumMs }) {
  if (!/^[0-9a-f]{40}$/.test(sha)) throw new Error(`${sha} is not a full commit SHA`);
  if (!["ahead", "identical"].includes(comparison))
    throw new Error(`${sha} is not on publicsuffix/list main`);
  if (!(Date.parse(committed) <= now - minimumMs))
    throw new Error(`${sha} was committed at ${committed}, inside the release-age gate`);
}

export function sourceFile({ sha, committed, list, tests }) {
  return `// Code generated by scripts/public-suffix-list.mjs. DO NOT EDIT.

package publicsuffix

// The commit of github.com/publicsuffix/list that public_suffix_list.dat and
// test_psl.txt were copied from, unchanged.
const (
	listCommit    = "${sha}"
	listCommitted = "${committed}"
	listSHA256    = "${sha256(list)}"
	testsSHA256   = "${sha256(tests)}"
)
`;
}

const json = async (url) => JSON.parse((await download(url)).toString("utf8"));

async function main(requested) {
  const now = Date.now();
  const minimumMs = minimumAgeMs(readFileSync(resolve(root, "pnpm-workspace.yaml"), "utf8"));
  const commit = requested
    ? await json(`${api}/commits/${requested}`)
    : (await json(`${api}/commits?sha=main&per_page=1&until=${new Date(now - minimumMs).toISOString()}`))[0];
  const sha = commit.sha;
  const committed = commit.commit.committer.date;
  const { status: comparison } = await json(`${api}/compare/${sha}...main`);
  checkCommit({ sha, committed, comparison, now, minimumMs });
  const downloaded = await Promise.all(files.map(([, path]) => download(`${raw}/${sha}/${path}`)));
  const [list, tests] = downloaded;
  if (!list.includes("// ===BEGIN PRIVATE DOMAINS===")) throw new Error("the downloaded list has no private section");
  files.forEach(([name], i) => writeFileSync(resolve(target, name), downloaded[i]));
  writeFileSync(resolve(target, "source.go"), sourceFile({ sha, committed, list, tests }));
  console.log(`Public Suffix List pinned to ${sha} (${committed})`);
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  await main(process.argv[2]);
}
