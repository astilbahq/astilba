// railpackpins writes the dashboard's copy of the Railpack pins this release builds with,
// so the dashboard checks a runner the way management does; see scripts/platform-generate.mjs.
package main

import (
	"fmt"

	"github.com/astilbahq/astilba/services/platform/internal/pipeline"
)

func main() {
	fmt.Printf(`// Code generated by services/platform/internal/pipeline/railpackpins. DO NOT EDIT.
// The Railpack pins this release builds with. A runner takes a Railpack build only when it
// advertises the same railpackInputs digest for its architecture.
export const railpackVersion = %q;
export const railpackInputs: Record<"amd64" | "arm64", string> = {
  amd64: %q,
  arm64: %q,
};
`, pipeline.RailpackVersion, pipeline.RailpackFor("amd64").Digest(), pipeline.RailpackFor("arm64").Digest())
}
